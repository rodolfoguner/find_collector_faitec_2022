CREATE TYPE TIPO_LIXO AS ENUM (
  'PAPEL',
  'VIDRO',
  'PLASTICO',
  'METAL',
  'ORGANICOS',
  'NAO_RECICLADOS'
);

CREATE TYPE TIPO_PESSOA AS ENUM (
  'RECICLADOR',
  'CATADOR'
);

CREATE TABLE
  IF NOT EXISTS estado(
    id SERIAL PRIMARY KEY,
    uf VARCHAR(2) NOT NULL UNIQUE,
    nome_estado VARCHAR(100) NOT NULL,
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    alterado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW()
  );

CREATE TABLE
  IF NOT EXISTS municipio(
    id SERIAL PRIMARY KEY,
    cidade VARCHAR(100) NOT NULL,
    estado_id INTEGER NOT NULL REFERENCES estado(id) ON UPDATE CASCADE ON DELETE NO ACTION,
    UNIQUE(cidade, estado_id),
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    alterado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW()
  );

CREATE TABLE
  IF NOT EXISTS pessoa(
    id SERIAL PRIMARY KEY,
    email VARCHAR(100) NOT NULL UNIQUE,
    senha VARCHAR(100),
    nome VARCHAR(100),
    telefone VARCHAR(15),
    cep VARCHAR(10),
    endereco VARCHAR(100),
    bairro VARCHAR(100),
    numero VARCHAR(10),
    tipo_pessoa TIPO_PESSOA NOT NULL DEFAULT 'RECICLADOR',
    tipo_lixo TIPO_LIXO[],
    descricao TEXT,
    ponto_coleta BOOLEAN DEFAULT FALSE,
    padrinho_id INTEGER REFERENCES pessoa(id) ON UPDATE CASCADE ON DELETE NO ACTION,
    municipio_id INTEGER REFERENCES municipio(id) ON UPDATE CASCADE ON DELETE NO ACTION,
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    alterado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW()
  );

CREATE TABLE
  IF NOT EXISTS coleta(
    id SERIAL PRIMARY KEY,
    data_e_hora TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    tipo_de_lixo TIPO_LIXO,
    aceito BOOLEAN NOT NULL DEFAULT FALSE,
    coletado BOOLEAN NOT NULL DEFAULT FALSE,
    recorrente BOOLEAN NOT NULL DEFAULT FALSE,
    cep VARCHAR(10),
    endereco VARCHAR(100) NOT NULL,
    bairro VARCHAR(100) NOT NULL,
    numero VARCHAR(10) NOT NULL,
    municipio_id INTEGER NOT NULL REFERENCES municipio(id) ON UPDATE CASCADE ON DELETE NO ACTION,
    catador_id INTEGER REFERENCES pessoa(id) ON UPDATE CASCADE ON DELETE NO ACTION,
    reciclador_id INTEGER NOT NULL REFERENCES pessoa(id) ON UPDATE CASCADE ON DELETE NO ACTION,
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    alterado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW()
  );
  
